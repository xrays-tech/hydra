function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved && LANGUAGES.some((l) => l.code === saved)) return saved;
  } catch { /* storage unavailable */ }
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("zh")) return "zh";
  if (nav.startsWith("fr")) return "fr";
  if (nav.startsWith("de")) return "de";
  return "en";
}

let LANG = detectLang();

function lookup(dict, key) {
  if (!dict) return undefined;
  // 扁平带点 key（如 "common.brand.sub" 作为字面属性名）优先；
  // 否则按嵌套路径遍历。
  if (key in dict && typeof dict[key] === "string") return dict[key];
  let node = dict;
  for (const part of key.split(".")) {
    if (node === null || typeof node !== "object" || !(part in node)) return undefined;
    node = node[part];
  }
  return typeof node === "string" ? node : undefined;
}

function t(key, vars) {
  const val = lookup(I18N[LANG], key) ?? lookup(I18N.en, key) ?? null;
  const s = val === null ? key : val;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}

function setLang(code) {
  if (!LANGUAGES.some((l) => l.code === code)) return;
  LANG = code;
  try { localStorage.setItem(LANG_STORAGE_KEY, code); } catch { /* ignore */ }
  document.documentElement.lang = code === "zh" ? "zh-CN" : code;
  if (typeof window.__onLangChanged === "function") window.__onLangChanged(code);
}

function currentLang() { return LANG; }

/* 静态外壳翻译：替换 [data-i18n]（textContent）、[data-i18n-html]（innerHTML，
 * 字典值可信）、[data-i18n-title]（title）、[data-i18n-placeholder]、
 * [data-i18n-aria-label]。 */
function applyStaticI18n(root = document) {
  for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll("[data-i18n-html]")) node.innerHTML = t(node.dataset.i18nHtml);
  for (const node of root.querySelectorAll("[data-i18n-title]")) node.title = t(node.dataset.i18nTitle);
  for (const node of root.querySelectorAll("[data-i18n-placeholder]")) node.placeholder = t(node.dataset.i18nPlaceholder);
  for (const node of root.querySelectorAll("[data-i18n-aria-label]")) node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
}

